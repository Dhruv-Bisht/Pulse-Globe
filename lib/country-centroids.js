function normalizeKey(name) {
  return String(name || "").trim().toLowerCase();
}

// Build a case-insensitive index once.
const INDEX = new Map();
for (const [name, coords] of Object.entries(COUNTRY_CENTROIDS)) {
  INDEX.set(normalizeKey(name), coords);
}

export function resolveCountryCentroid(name) {
  const key = normalizeKey(name);
  if (!key) return null;
  if (INDEX.has(key)) return INDEX.get(key);
  if (ALIASES[key]) return INDEX.get(normalizeKey(ALIASES[key])) || null;
  // Loose contains-match as a last resort (handles things like
  // "Congo, Democratic Republic of" vs "Democratic Republic of Congo").
  for (const [indexedName, coords] of INDEX.entries()) {
    if (indexedName.includes(key) || key.includes(indexedName)) return coords;
  }
  return null;
}
